#!/usr/bin/env python3
"""Generate the paper's AI-usage disclosure from the record, never from memory (Stage 21; JOSS).

It reads two sources at one commit:
- the ``model`` and ``claude_code_version`` fields of every post-stage handoff's frontmatter;
- the ``Co-Authored-By`` trailers of the commits reachable from it.

It writes a block between ``<!-- AI-INVENTORY:START -->`` and ``<!-- AI-INVENTORY:END -->`` in
``paper/paper.md``. The human-review statement next to it is the operator's own words and is never
generated.

    python3 -I scripts/ai_usage_inventory.py --write [--ref origin/main]
    python3 -I scripts/ai_usage_inventory.py --check [--ref HEAD] [--max-behind 1]  # stale -> 1

The block names the commit it was generated at, and a commit cannot contain its own hash, so
``--check`` does not regenerate at ``--ref``. It regenerates at the commit the block names and
requires that commit to be an ancestor of ``--ref``, at most ``--max-behind`` commits back. The
default of 1 allows exactly the PR that wrote the block.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
START, END = "<!-- AI-INVENTORY:START -->", "<!-- AI-INVENTORY:END -->"
STAMP = re.compile(r"commit trailers at `([^`]+)` \(`([0-9a-f]{7,40})`\)")
HANDOFF = re.compile(r"STAGE-.*-DONE-.*\.md")


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=repo, capture_output=True, text=True, check=True
    ).stdout


def _field(text: str, name: str) -> str:
    front = text.split("---", 2)[1] if text.startswith("---") else ""
    m = re.search(rf"^{name}:\s*(.+?)\s*$", front, re.M)
    return m.group(1).strip().strip("\"'") if m else ""


def _ranges(stages: list[int]) -> str:
    stages = sorted(stages)
    out, start = [], stages[0]
    for prev, cur in zip(stages, [*stages[1:], None], strict=True):
        if cur != prev + 1:
            out.append(f"{start}" if start == prev else f"{start}\u2013{prev}")
            if cur is not None:
                start = cur
    return ", ".join(out)


def block(repo: Path, label: str, commit: str) -> str:
    """The disclosure as of ``commit`` (handoffs and trailers both read there), labelled ``label``."""
    by_model: dict[str, list[int]] = defaultdict(list)
    names = _git(repo, "ls-tree", "--name-only", f"{commit}:docs/handoffs").split()
    for name in sorted(n for n in names if HANDOFF.fullmatch(n)):
        text = _git(repo, "show", f"{commit}:docs/handoffs/{name}")
        stage = int(_field(text, "stage") or 0)
        model = re.sub(r"\[.*?\]$", "", _field(text, "model")) or "unrecorded"
        by_model[model].append(stage)
    sha = _git(repo, "rev-parse", "--short=12", commit).strip()
    log = _git(
        repo,
        "log",
        commit,
        "--format=%x1e%(trailers:key=Co-Authored-By,valueonly,separator=%x1f)",
    )
    commits = [c for c in log.split("\x1e") if c != ""]
    with_ai = sum(1 for c in commits if re.search(r"\bClaude\b", c))
    models = "; ".join(
        f"`{m}` (Stage{'s' if len(s) > 1 else ''} {_ranges(s)})"
        for m, s in sorted(by_model.items(), key=lambda kv: min(kv[1]))
    )
    stages = sorted(s for v in by_model.values() for s in v)
    return (
        f"{START}\n"
        f"*Generated by `scripts/ai_usage_inventory.py` from the post-stage handoffs and the commit "
        f"trailers at `{label}` (`{sha}`).*\n\n"
        f"Every stage of the build ({_ranges(stages)}) was carried out in Claude Code sessions "
        f"(Anthropic) by an AI coding agent that wrote most of the code, tests and documentation, under "
        f"the direction of the author. The models, as recorded in each stage's handoff, were: {models}. "
        f"Of the {len(commits)} commits on `{label}`, {with_ai} carry a Claude `Co-Authored-By` trailer. "
        f"The author directed every stage and accepted every architecture decision record and "
        f"pre-registration. Merges and releases were the author's acts, or ran under the author's "
        f"standing approval.\n"
        f"{END}"
    )


def check(repo: Path, current: str, ref: str, max_behind: int) -> str | None:
    """None if ``current`` is the true disclosure at a recent ancestor of ``ref``, else the reason."""
    stamp = STAMP.search(current)
    if stamp is None:
        return "the block names no commit (run --write)"
    label, short = stamp.groups()
    try:
        commit = _git(repo, "rev-parse", "--verify", "-q", f"{short}^{{commit}}").strip()
    except subprocess.CalledProcessError:
        return f"the block names {short}, which is not a commit here"
    tip = _git(repo, "rev-parse", "--verify", f"{ref}^{{commit}}").strip()
    if subprocess.run(["git", "merge-base", "--is-ancestor", commit, tip], cwd=repo).returncode:
        return f"the block's commit {short} is not an ancestor of {ref}"
    behind = int(_git(repo, "rev-list", "--count", f"{commit}..{tip}").strip())
    if behind > max_behind:
        return f"the block is {behind} commits behind {ref} (at most {max_behind}): run --write"
    if current != block(repo, label, commit):
        return f"the block differs from the record at {short}: run --write and review it"
    return None


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("--ref", default=None, help="--write: origin/main; --check: HEAD (defaults)")
    ap.add_argument("--max-behind", type=int, default=1)
    ap.add_argument("--repo", type=Path, default=REPO)
    ap.add_argument("--paper", type=Path, default=None)
    a = ap.parse_args(argv)
    paper = a.paper or a.repo / "paper" / "paper.md"
    text = paper.read_text(encoding="utf-8")
    m = re.search(re.escape(START) + r".*?" + re.escape(END), text, re.S)
    if m is None:
        print(f"{paper} has no {START} ... {END} block", file=sys.stderr)
        return 1
    if a.check:
        problem = check(a.repo, m.group(0), a.ref or "HEAD", a.max_behind)
        if problem is not None:
            print(f"the AI-usage disclosure is stale: {problem}", file=sys.stderr)
            return 1
        print("AI-usage disclosure is current")
        return 0
    ref = a.ref or "origin/main"
    fresh = block(a.repo, ref, ref)
    paper.write_text(text[: m.start()] + fresh + text[m.end() :], encoding="utf-8", newline="\n")
    print(f"wrote the AI-usage disclosure into {paper}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
